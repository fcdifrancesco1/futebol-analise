const TEAM_COLORS_DEFAULT = ["#1d2a45", "#101828"];

function teamColors(teamId) {
  return TEAM_COLORS[teamId] || TEAM_COLORS_DEFAULT;
}

// style="--c1:..;--c2:.." para as barras (classificação, líderes, heróis).
function teamColorVars(teamId) {
  const [c1, c2] = teamColors(teamId);
  return `--c1:${c1};--c2:${c2}`;
}

// style="--h1:..;--a1:.." para a linha da partida pintada meio a meio (mandante | visitante).
function matchColorVars(homeId, awayId) {
  return `--h1:${teamColors(homeId)[0]};--a1:${teamColors(awayId)[0]}`;
}

